export function detectLanguage() {
  const saved = localStorage.getItem("bep-language");
  if (saved && translations[saved]) return saved;

  const browserLanguage = navigator.language.toLowerCase();
  if (browserLanguage.startsWith("ht")) return "ht";
  if (browserLanguage.startsWith("en")) return "en";
  return "fr";
}

export function applyTranslations(language) {
  const dictionary = translations[language] || translations.fr;

  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[key]) element.setAttribute("placeholder", dictionary[key]);
  });

  localStorage.setItem("bep-language", language);
  return dictionary;
}
